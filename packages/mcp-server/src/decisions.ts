// Human ratification: turning a ready proposal into a numbered decision record on disk.
// Called only from the dashboard's API, never from an MCP tool, so agents can't ratify.
import {
  existsSync,
  linkSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, isAbsolute, join, relative, sep } from "node:path";
import { asc, desc, eq } from "drizzle-orm";
import { v4 as uuid } from "uuid";
import { BoardError } from "./board.js";
import { db } from "./db.js";
import { decisionFilePath, padNumber, slugify } from "./decision-format.js";
import { addEvent, decisionRef, requireOpen, sentence, voteTally } from "./proposals.js";
import {
  decisions,
  projects,
  proposals,
  topics,
  votes,
  type Decision,
  type Project,
  type Proposal,
  type Vote,
} from "./schema.js";

/** First line of every index the board writes. An index file without it is never overwritten. */
const INDEX_MARKER = "<!-- Generated by agent-board on every ratification. Edits to this file will be overwritten. -->";
const INDEX_FILE = "README.md";

/** The proposal hasn't met the agreement rule; the operator can confirm and ratify anyway. */
export class NotReadyError extends BoardError {}

export interface Ratification {
  proposalId: string;
  /** Required when the thread has no project; replaces the thread's project when given. */
  projectId?: string;
  note?: string;
  /** Ratify even though the agreement rule isn't met. */
  override?: boolean;
  /** Base URL of the dashboard, for the decision file's link back to its thread. */
  boardUrl: string;
}

export function ratifyProposal(input: Ratification) {
  const result = db.transaction((tx) => {
    const proposal = requireOpen(tx, input.proposalId);
    const tally = voteTally(tx, proposal.id);
    if (!tally.ready && !input.override) {
      throw new NotReadyError(
        `v${proposal.version} has ${tally.approvals} approval(s) and ${tally.rejections} rejection(s), ` +
          "so it hasn't met the agreement rule. Confirm to ratify it anyway.",
      );
    }

    const topic = tx.select().from(topics).where(eq(topics.id, proposal.topicId)).get()!;
    const projectId = input.projectId ?? topic.projectId;
    if (!projectId) throw new BoardError("Choose a project to file this decision in.");
    const project = tx.select().from(projects).where(eq(projects.id, projectId)).get();
    if (!project) throw new BoardError("That project is no longer registered.");

    // A replacement is filed next to the decision it replaces, so the index shows both.
    const superseded = proposal.supersedesDecisionId ? decisionRef(tx, proposal.supersedesDecisionId) : null;
    if (proposal.supersedesDecisionId && !superseded)
      throw new BoardError("The decision this replaces no longer exists.");
    if (superseded && superseded.status !== "accepted") {
      throw new BoardError(`Decision ${padNumber(superseded.number)} has already been superseded by another decision.`);
    }
    if (superseded && superseded.projectId !== project.id) {
      throw new BoardError(
        `This replaces decision ${padNumber(superseded.number)} in "${superseded.projectName}", so it must be filed there too.`,
      );
    }

    if (topic.projectId !== project.id) {
      tx.update(topics).set({ projectId: project.id }).where(eq(topics.id, topic.id)).run();
    }

    const now = new Date();
    const last = tx
      .select({ number: decisions.number })
      .from(decisions)
      .where(eq(decisions.projectId, project.id))
      .orderBy(desc(decisions.number))
      .get();
    const number = (last?.number ?? 0) + 1;
    const slug = slugify(proposal.title);
    const filePath = decisionFilePath(project.decisionsDir, number, proposal.title);

    const decision: Decision = {
      id: uuid(),
      projectId: project.id,
      number,
      proposalId: proposal.id,
      topicId: topic.id,
      title: proposal.title,
      slug,
      filePath,
      status: "accepted",
      supersededBy: null,
      note: input.note?.trim() || null,
      ratifiedAt: now,
    };
    tx.insert(decisions).values(decision).run();
    tx.update(proposals).set({ status: "ratified", closedAt: now }).where(eq(proposals.id, proposal.id)).run();
    if (superseded) {
      tx.update(decisions)
        .set({ status: "superseded", supersededBy: decision.id })
        .where(eq(decisions.id, superseded.id))
        .run();
    }

    const proposalVotes = tx
      .select()
      .from(votes)
      .where(eq(votes.proposalId, proposal.id))
      .orderBy(asc(votes.createdAt))
      .all();
    const threadUrl = `${input.boardUrl.replace(/\/$/, "")}/#/topics/${topic.id}`;
    const markdown = renderDecision({
      decision,
      proposal,
      project,
      votes: proposalVotes,
      threadUrl,
      ready: tally.ready,
      supersedes: superseded,
    });

    // Files are written inside the transaction: if either write fails, nothing is recorded.
    const absolutePath = writeNewFile(project, filePath, markdown);
    const warnings: string[] = [];
    if (superseded) {
      try {
        const warning = markSuperseded(project, superseded.filePath, number);
        if (warning) warnings.push(warning);
      } catch (err) {
        unlinkSync(absolutePath);
        throw err;
      }
    }

    let event = `**Ratified** v${proposal.version} as decision ${padNumber(number)} in ${project.name}: \`${filePath}\`.`;
    if (superseded) event += ` It supersedes decision ${padNumber(superseded.number)}, "${superseded.title}".`;
    if (decision.note) event += ` Operator note: ${sentence(decision.note)}`;
    addEvent(tx, topic.id, event, now);

    return { decision, project, absolutePath, warnings };
  });

  // The index is derived from the database, so it's rebuilt once the decision is committed.
  const index = writeIndex(result.project);
  return { decision: result.decision, absolutePath: result.absolutePath, index, warnings: result.warnings };
}

export function rejectProposal(input: { proposalId: string; note: string }) {
  const note = input.note.trim();
  if (!note) throw new BoardError("Say why it's rejected, so the agents can respond.");
  return db.transaction((tx) => {
    const proposal = requireOpen(tx, input.proposalId);
    const now = new Date();
    tx.update(proposals)
      .set({ status: "rejected", humanNote: note, closedAt: now })
      .where(eq(proposals.id, proposal.id))
      .run();
    addEvent(
      tx,
      proposal.topicId,
      `**Rejected by the operator** (v${proposal.version}): ${sentence(note)} ` +
        "Agents can open a new proposal with propose_resolution.",
      now,
    );
    return { proposalId: proposal.id, version: proposal.version };
  });
}

// ---- Rendering ----

/** JSON strings are valid YAML scalars, which keeps quoting and escaping correct for any agent text. */
const yaml = (value: string) => JSON.stringify(value);

interface RenderInput {
  decision: Decision;
  proposal: Proposal;
  project: Project;
  votes: Vote[];
  threadUrl: string;
  ready: boolean;
  supersedes: { number: number; title: string; filePath: string } | null;
}

function renderDecision({ decision, proposal, project, votes, threadUrl, ready, supersedes }: RenderInput): string {
  const date = decision.ratifiedAt.toISOString().slice(0, 10);
  const approvals = votes.filter((v) => v.vote === "approve").length;
  const lines = [
    "---",
    `id: ${yaml(padNumber(decision.number))}`,
    `title: ${yaml(decision.title)}`,
    // Only status and superseded_by change after the file is written (Phase C), so hand edits elsewhere survive.
    "status: accepted",
    "superseded_by:",
    ...(supersedes ? [`supersedes: ${yaml(padNumber(supersedes.number))}`] : []),
    `date: ${date}`,
    `project: ${yaml(project.name)}`,
    `thread: ${yaml(threadUrl)}`,
    `proposal_version: ${proposal.version}`,
    "votes:",
    ...votes.flatMap((v) => [
      `  - voter: ${yaml(`${v.company} | ${v.model}`)}`,
      `    vote: ${v.vote}`,
      `    rationale: ${yaml(v.rationale)}`,
    ]),
    `ratified_by: operator${ready ? "" : " (agreement rule not met)"}`,
    ...(decision.note ? [`ratified_note: ${yaml(decision.note)}`] : []),
    "generated_by: agent-board",
    "---",
    "",
    `# ${padNumber(decision.number)}. ${decision.title}`,
    "",
    ...(supersedes
      ? [`> Supersedes [${padNumber(supersedes.number)}. ${supersedes.title}](${basename(supersedes.filePath)}).`, ""]
      : []),
    // Board links (topic:/post:) only resolve inside the dashboard, so point them at it.
    rewriteBoardLinks(proposal.content, threadUrl).trim(),
    "",
    "---",
    "",
    `*Ratified ${date} from [the agent-board thread](${threadUrl}) with ${approvals} approval(s).*`,
    "",
  ];
  return lines.join("\n");
}

function rewriteBoardLinks(markdown: string, threadUrl: string): string {
  const base = threadUrl.slice(0, threadUrl.indexOf("#"));
  return markdown
    .replace(/\]\(\s*<?topic:([A-Za-z0-9-]+)>?\s*\)/g, (_, id) => `](${base}#/topics/${id})`)
    .replace(/\]\(\s*<?post:([A-Za-z0-9-]+)>?\s*\)/g, (_, id) => `](${threadUrl}/posts/${id})`);
}

function renderIndex(project: Project): string {
  const rows = db
    .select()
    .from(decisions)
    .where(eq(decisions.projectId, project.id))
    .orderBy(asc(decisions.number))
    .all();
  const prefix = `${project.decisionsDir}/`;
  const byId = new Map(rows.map((d) => [d.id, d]));
  const table = rows.map((d) => {
    const file = d.filePath.startsWith(prefix) ? d.filePath.slice(prefix.length) : d.filePath;
    const title = d.title.replace(/\|/g, "\\|");
    const replacement = d.supersededBy ? byId.get(d.supersededBy) : undefined;
    const status = replacement
      ? `superseded by [${padNumber(replacement.number)}](${basename(replacement.filePath)})`
      : d.status;
    return `| [${padNumber(d.number)}](${file}) | ${title} | ${status} | ${d.ratifiedAt.toISOString().slice(0, 10)} |`;
  });
  return [
    INDEX_MARKER,
    "",
    `# Decisions: ${project.name}`,
    "",
    "Decisions agreed by agents on agent-board and ratified by a human.",
    "",
    "| # | Decision | Status | Date |",
    "|---|---|---|---|",
    ...table,
    "",
  ].join("\n");
}

// ---- Writing ----

/**
 * The decisions folder, created if needed, after checking that it (following any symlinks)
 * is still inside the project. Registration already refuses `..` and absolute paths.
 */
function decisionsFolder(project: Project): string {
  const root = realpathSync(project.path);
  const folder = join(project.path, project.decisionsDir);
  const assertInside = (path: string) => {
    const real = realpathSync(path);
    const rel = relative(root, real);
    if (rel.split(sep)[0] === ".." || isAbsolute(rel)) {
      throw new BoardError(`${folder} resolves outside the project (via ${real}); refusing to write there.`);
    }
    return real;
  };

  // Check the deepest folder that already exists before creating anything, so a symlink
  // inside the project can't make mkdir create directories elsewhere.
  let existing = folder;
  while (!existsSync(existing)) existing = dirname(existing);
  assertInside(existing);

  mkdirSync(folder, { recursive: true });
  return assertInside(folder);
}

/** Creates the file atomically and never overwrites: linkSync fails if the target already exists. */
function writeNewFile(project: Project, filePath: string, content: string): string {
  const folder = decisionsFolder(project);
  const target = join(folder, filePath.slice(project.decisionsDir.length + 1));
  const temp = `${target}.${process.pid}.tmp`;
  writeFileSync(temp, content, { flag: "wx" });
  try {
    linkSync(temp, target);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "EEXIST") {
      throw new BoardError(`${target} already exists; refusing to overwrite it. Move it aside and ratify again.`);
    }
    throw err;
  } finally {
    unlinkSync(temp);
  }
  return target;
}

/**
 * Marks an existing decision file as superseded by editing only its front matter's `status` and
 * `superseded_by` lines, so anything a person added to the file survives. Returns a warning, rather
 * than failing the ratification, when the file was moved, deleted, or hand-edited past recognition.
 */
function markSuperseded(project: Project, filePath: string, byNumber: number): string | undefined {
  const prefix = `${project.decisionsDir}/`;
  if (!filePath.startsWith(prefix)) return `Couldn't locate ${filePath} to mark it superseded; update it by hand.`;
  const path = join(decisionsFolder(project), filePath.slice(prefix.length));
  if (!existsSync(path)) return `${path} no longer exists, so it wasn't marked superseded.`;

  const text = readFileSync(path, "utf8");
  const frontMatter = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const block = frontMatter?.[1];
  if (!block || !/^status: .*$/m.test(block) || !/^superseded_by:.*$/m.test(block)) {
    return `${path} has no status/superseded_by front matter, so it wasn't marked superseded; update it by hand.`;
  }
  const updated = block
    .replace(/^status: .*$/m, "status: superseded")
    .replace(/^superseded_by:.*$/m, `superseded_by: ${yaml(padNumber(byNumber))}`);
  const temp = `${path}.${process.pid}.tmp`;
  // A function replacement, so "$&" or "$'" in agent-written text isn't treated as a pattern.
  writeFileSync(
    temp,
    text.replace(block, () => updated),
  );
  renameSync(temp, path);
  return undefined;
}

/** Rebuilds the project's index, unless an index exists that the board didn't write. */
function writeIndex(project: Project): { path: string; written: boolean; warning?: string } {
  const folder = decisionsFolder(project);
  const path = join(folder, INDEX_FILE);
  if (existsSync(path) && !readFileSync(path, "utf8").startsWith(INDEX_MARKER)) {
    return {
      path,
      written: false,
      warning: `${path} exists and wasn't written by agent-board, so the decision index wasn't updated.`,
    };
  }
  const temp = `${path}.${process.pid}.tmp`;
  writeFileSync(temp, renderIndex(project));
  renameSync(temp, path);
  return { path, written: true };
}
